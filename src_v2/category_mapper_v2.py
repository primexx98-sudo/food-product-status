def _match(text: str, tier: str) -> str | None:
    t = text.lower()
    for cat in GENERAL_CAT_LIST:
        spec = _MAP.get(cat)
        if not spec:
            continue
        if any(kw.lower() in t for kw in spec.get(tier, [])):
            return cat
    return None


def categorize_general_food_v2(product_name: str, raw_material: str = '', report_no: str = '') -> str:
    name = str(product_name or '')
    raw = str(raw_material or '')
    raw_masked = raw
    for m in _RAW_MASK:
        raw_masked = raw_masked.replace(m, '')
    for m in _NAME_MASK:
        name = name.replace(m, '')

    # 1단계: 품목명 공정 키워드 (전 카테고리) — 다른 어떤 매칭보다 우선
    result = _match(name, 'process')
    if result:
        return result

    # 2단계: 품목명 강한 키워드
    result = _match(name, 'strong')
    if result:
        return result

    # 3단계: 원재료명 강한 키워드
    for cat in GENERAL_CAT_LIST:
        spec = _MAP.get(cat)
        if spec and any(kw.lower() in raw_masked.lower() for kw in spec.get('raw', [])):
            return cat

    # 4단계: 품목명 약한 키워드
    result = _match(name, 'weak')
    if result:
        return result

    return '기타'
