# 원재료명 텍스트에서 매칭 전 제거할 문자열 — 우연히 다른 원료명과 글자가 겹치는 식품첨가물명.
# 2026-08-28: "구연산삼나트륨"(구연산+삼나트륨, 흔한 첨가물)에 "산삼"이 우연히 포함돼
# 에너지 카테고리가 181건 대량 오매칭되는 문제 발견 — 원재료 매칭 전 마스킹으로 제거.
_RAW_MASK = ['구연산삼나트륨']

# 인터뷰 완료 표시 — 여기 있는 카테고리만 v2가 "확정 판단"한 것으로 간주.
DONE: set[str] = {'피부', '에너지', '효소'}


def _match(text: str, tier: str) -> str | None:
    t = text.lower()
    for cat in GENERAL_CAT_LIST:
        spec = _MAP.get(cat)
        if not spec:
            continue
        if any(kw.lower() in t for kw in spec.get(tier, [])):
            return cat
    return None


def categorize_general_food_v2(product_name: str, raw_material: str = '', report_no: str = '') -> str:
    name = str(product_name or '')
    raw = str(raw_material or '')
    raw_masked = raw
    for m in _RAW_MASK:
        raw_masked = raw_masked.replace(m, '')

    # 1단계: 품목명 공정 키워드 (전 카테고리) — 다른 어떤 매칭보다 우선
    result = _match(name, 'process')
    if result:
        return result

    # 2단계: 품목명 강한 키워드
    result = _match(name, 'strong')
    if result:
        return result

    # 3단계: 원재료명 강한 키워드
    for cat in GENERAL_CAT_LIST:
        spec = _MAP.get(cat)
        if spec and any(kw.lower() in raw_masked.lower() for kw in spec.get('raw', [])):
            return cat

    # 4단계: 품목명 약한 키워드
    result = _match(name, 'weak')
    if result:
        return result

    return '기타'
