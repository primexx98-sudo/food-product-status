def _match(text: str, keyword_map: list) -> str | None:
    text_lower = text.lower()
    for category, keywords in keyword_map:
        for kw in keywords:
            if kw.lower() in text_lower:
                return category
    return None


def categorize_health_food(fnclty_cn: str) -> str:
    return _match(fnclty_cn, _HEALTH_MAP) or '기타'


def categorize_general_food(product_name: str, raw_material: str) -> str:
    return _match(product_name, _GENERAL_MAP) or _match(raw_material, _GENERAL_MAP) or '기타'
