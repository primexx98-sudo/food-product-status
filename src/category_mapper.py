    # 제품도 규칙 6의 키워드 매칭을 먼저 거치고, 매칭 안 되면 기존과 동일하게 기타로 떨어짐.

    # 규칙 4-1 (src_v2 인터뷰, 2026-08-28): 효소분해/발효효소/효소처리 등 제조 공정을
    # 명시한 품목명은 다른 카테고리의 강한 원료명 키워드보다 우선해 효소로 분류.
