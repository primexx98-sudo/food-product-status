def is_general_excluded(product_name: str, report_no: str = '', company: str = '') -> bool:
    name = str(product_name or '').strip()
    if str(report_no or '') in _GENERAL_EXCLUDE_REPORT_NOS:
        return True
    if str(company or '').strip() in _GENERAL_EXCLUDE_COMPANIES:
        return True
    if any(name.endswith(s) for s in _GENERAL_EXCLUDE_SUFFIXES):
        return True
    if any(kw in name for kw in _GENERAL_EXCLUDE_CONTAINS):
        return True
    if _GENERAL_EXCLUDE_CODE_MIX_RE.match(name):
        return True
    return bool(_GENERAL_EXCLUDE_EN_PAREN_RE.search(name))


def _extract_bracket_items(text: str) -> list[str]:
    """주된기능성에서 [원료명] 형식의 기능성 원료명 추출"""
    return re.findall(r'\[([^\]]{1,40})\]', text)


def _match_items(items: list[str], keyword_map: list) -> str | None:
    for cat, keywords in keyword_map:
        for kw in keywords:
            kw_l = kw.lower()
            for item in items:
                if kw_l in item.lower():
                    return cat
    return None


def _match_text(text: str, keyword_map: list) -> str | None:
    t_lower = text.lower()
    for cat, keywords in keyword_map:
        for kw in keywords:
            if kw.lower() in t_lower:
                return cat
    return None


def _strip_flavor_tokens(raw_material: str) -> str:
    """원재료명 토큰 중 향료류(실제 원료가 아닌 향 첨가물) 제거.

    '블루베리향'/'블루베리향분말'처럼 향료명이 실제 원료명과 우연히 겹쳐
    항산화 등 카테고리에 오매칭되는 문제 방지 (2026-07 피로개선/항산화 검토에서 발견).
    """
    tokens = re.split(r'[,]+', raw_material)
    kept = [
        t for t in tokens
        if not ('향료' in t or t.strip().endswith(('향', '향분말', '향추출물', '향제제')))
    ]
    return ','.join(kept)


def categorize_health_food(fnclty_cn: str, product_name: str = '', raw_material: str = '') -> str:
    text = str(fnclty_cn or '')
    name = str(product_name or '')
    raw = str(raw_material or '')

    # 1. 제품명으로 멀티팩 감지
    name_l = name.lower()
    if any(kw in name_l for kw in _MULTIPACK_NAME_KEYWORDS):
        return '멀티팩'

    # 2. [원료명] 괄호 추출
    items = _extract_bracket_items(text)

    # 2-1. 원료가 10개 이상이면 복합 멀티팩으로 처리
    if len(items) >= 10:
        return '멀티팩'

    # 3. 비타민/미네랄만 있는 경우 → 즉시 비타민 (뼈건강 명시 시 뼈건강 우선)
    if items and _is_vitamin_mineral_only(items):
        if any(kw in text for kw in _BONE_TEXT_KWS):
            return '뼈건강'
        return '비타민'

    # 4. 원료명 기준 우선순위 매칭 (가장 정확)
    if items:
        result = _match_items(items, _HEALTH_MAP)
        if result:
            return result

    # 5. 주된기능성 전체 텍스트 매칭 (구형/서술형 포맷 대응)
    result = _match_text(text, _HEALTH_MAP)
    if result:
        return result

    # 6. 제품명 → 원재료 순으로 보조 매칭
    result = _match_text(name, _HEALTH_MAP) or _match_text(raw, _HEALTH_MAP)
    if result:
        return result

    return '기타'


